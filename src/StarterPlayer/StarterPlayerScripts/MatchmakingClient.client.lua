leaveCorner.Parent = leaveButton

local function applyUpdate(payload)
	if not payload.inQueue then
		gui.Enabled = false
		return
	end

	gui.Enabled = true
	title.Text = string.format("Warteschlange — %s", payload.modeLabel or "Match")

	local queueLine = string.format(
		"Spieler: %d / %d",
		payload.queueSize or 0,
		payload.required or 0
	)
	if payload.status == "pending" then
		queueLine = queueLine .. "  •  Arena belegt"
	end

	status.Text = string.format(
		"%s\n%s",
		payload.message or "Suche Match...",
		queueLine
	)
end

Remotes.QueueUpdate.OnClientEvent:Connect(applyUpdate)

leaveButton.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
end)
