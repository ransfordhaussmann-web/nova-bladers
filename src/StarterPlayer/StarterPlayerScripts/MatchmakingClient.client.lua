local function statusText(payload)
	if payload.status == "pending" then
		return "Arena belegt — du bist in der Warteschlange.\nPlatz: " .. tostring(payload.position or "?")
	end
	if payload.status == "starting" then
		return "Match startet gleich..."
	end
	return string.format(
		"%s: %d / %d Spieler\nPlatz in Queue: %d",
		payload.modeLabel or payload.modeId or "Modus",
		payload.count or 0,
		payload.maxPlayers or 0,
		payload.position or 0
	)
end

Remotes.QueueUpdate.OnClientEvent:Connect(function(payload)
	if not payload.inQueue then
		gui.Enabled = false
		return
	end

	gui.Enabled = true
	title.Text = "Queue: " .. (payload.modeLabel or payload.modeId or "?")
	status.Text = statusText(payload)
end)

leaveBtn.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
	gui.Enabled = false
end)

Remotes.HubState.OnClientEvent:Connect(function(statePayload)
	if statePayload.phase == "arena" then
		gui.Enabled = false
	end
end)
