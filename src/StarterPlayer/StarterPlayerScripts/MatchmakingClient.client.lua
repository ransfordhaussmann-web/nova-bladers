local STATUS_TEXT = {
	waiting = "Warte auf Mitspieler...",
	pending = "Arena belegt — du bist vorgemerkt",
	filling = "Lobby füllt sich — Match startet bald",
}

local function formatStatus(payload)
	local base = string.format(
		"%s\n%d / %d Spieler",
		payload.modeLabel or payload.modeId or "Match",
		payload.queued or 0,
		payload.maxPlayers or payload.minPlayers or 1
	)
	local hint = STATUS_TEXT[payload.status]
	if hint then
		return base .. "\n" .. hint
	end
	return base
end

Remotes.QueueUpdate.OnClientEvent:Connect(function(payload)
	if not payload.inQueue then
		gui.Enabled = false
		return
	end

	gui.Enabled = true
	title.Text = "Warteschlange — " .. (payload.modeLabel or payload.modeId or "")
	statusLabel.Text = formatStatus(payload)
end)

leaveBtn.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
	gui.Enabled = false
end)

Remotes.HubState.OnClientEvent:Connect(function(state)
	if state.phase == "arena" then
		gui.Enabled = false
	end
end)
