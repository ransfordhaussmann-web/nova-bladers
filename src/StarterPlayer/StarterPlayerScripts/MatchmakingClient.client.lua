local function statusText(payload)
	if payload.status == "pending" then
		return "Arena belegt — du bist als Nächster dran."
	end
	if payload.status == "filling" and payload.fillSecondsLeft then
		return string.format(
			"%s: %d/%d Spieler — Start in %ds",
			payload.modeLabel,
			payload.playersInQueue,
			payload.maxPlayers,
			payload.fillSecondsLeft
		)
	end
	return string.format(
		"%s: %d/%d Spieler",
		payload.modeLabel,
		payload.playersInQueue,
		payload.maxPlayers
	)
end

Remotes.QueueUpdate.OnClientEvent:Connect(function(payload)
	if not payload or not payload.inQueue then
		gui.Enabled = false
		return
	end

	gui.Enabled = true
	title.Text = "Warteschlange — " .. payload.modeLabel
	status.Text = statusText(payload)
end)

leaveButton.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
	gui.Enabled = false
end)
