local function hideQueue()
	gui.Enabled = false
end

local function showQueue(payload)
	gui.Enabled = true
	title.Text = "Warteschlange: " .. (payload.modeLabel or payload.modeId or "?")

	if payload.status == "pending" then
		status.Text = string.format(
			"Arena belegt — warte...\n%d Spieler bereit",
			payload.playersInQueue or 0
		)
	elseif payload.status == "starting" then
		status.Text = "Match startet gleich..."
		leaveButton.Visible = false
	else
		local needed = payload.playersNeeded or 1
		local inQueue = payload.playersInQueue or 0
		status.Text = string.format(
			"%d / %d Spieler\nPosition: %d",
			inQueue,
			needed,
			payload.position or inQueue
		)
		leaveButton.Visible = true
	end
end

Remotes.QueueUpdate.OnClientEvent:Connect(function(payload)
	if payload.status == "left" then
		hideQueue()
		return
	end
	if payload.status == "starting" then
		showQueue(payload)
		task.delay(2, hideQueue)
		return
	end
	showQueue(payload)
end)

Remotes.HubState.OnClientEvent:Connect(function(state)
	if state.phase == "arena" then
		hideQueue()
	end
end)

leaveButton.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
	hideQueue()
end)
