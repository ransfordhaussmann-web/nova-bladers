local function hideQueue()
	gui.Enabled = false
end

local function showQueue(payload)
	gui.Enabled = true
	title.Text = payload.pending
		and string.format("⏳ %s — Arena belegt", payload.modeLabel or "Match")
		or string.format("⏳ %s", payload.modeLabel or "Warteschlange")

	local lines = {
		string.format(
			"Spieler: %d / %d",
			payload.playersWaiting or 0,
			payload.maxPlayers or payload.minPlayers or 1
		),
	}

	if payload.fillRemaining then
		lines[#lines + 1] = string.format("Start in ~%ds", math.ceil(payload.fillRemaining))
	elseif payload.pending then
		lines[#lines + 1] = "Warte bis die Arena frei ist..."
	else
		lines[#lines + 1] = "Warte auf weitere Spieler..."
	end

	status.Text = table.concat(lines, "\n")
end

Remotes.QueueUpdate.OnClientEvent:Connect(function(payload)
	if payload.inQueue then
		showQueue(payload)
	else
		hideQueue()
	end
end)

leaveBtn.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
	hideQueue()
end)
