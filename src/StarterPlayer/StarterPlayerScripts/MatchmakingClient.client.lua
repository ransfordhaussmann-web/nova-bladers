local STATUS_TEXT = {
	waiting = "Warte auf Spieler…",
	filling = "Lobby füllt sich — Start in Kürze",
	ready = "Match startet…",
	pending = "Arena belegt — du bist als Nächster dran",
}

local function formatPlayerList(names)
	if #names == 0 then
		return "Noch keine Spieler"
	end
	if #names <= 4 then
		return table.concat(names, ", ")
	end
	local short = {}
	for i = 1, 4 do
		table.insert(short, names[i])
	end
	return table.concat(short, ", ") .. string.format(" +%d", #names - 4)
end

local function applyQueueUpdate(payload)
	if not payload.inQueue then
		gui.Enabled = false
		return
	end

	gui.Enabled = true
	title.Text = string.format("Warteschlange — %s", payload.modeLabel or "Match")
	statusLabel.Text = string.format(
		"%s\n%d / %d Spieler\n%s",
		STATUS_TEXT[payload.status] or "In Warteschlange…",
		payload.count or 0,
		payload.maxPlayers or 0,
		formatPlayerList(payload.playerNames or {})
	)
end

Remotes.QueueUpdate.OnClientEvent:Connect(applyQueueUpdate)

Remotes.HubState.OnClientEvent:Connect(function(state)
	if state.phase == "arena" then
		gui.Enabled = false
	end
end)

leaveButton.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
	gui.Enabled = false
end)
