leaveCorner.Parent = leaveButton

local function formatStatus(payload)
	if payload.status == "starting" then
		return string.format("Match startet — %s", payload.label or payload.modeId or "")
	end
	if payload.status == "pending" then
		return string.format(
			"%s\nArena belegt — Position %d/%d (wartet auf freie Arena)",
			payload.label or payload.modeId,
			payload.position,
			payload.maxPlayers
		)
	end
	return string.format(
		"%s\nSpieler %d/%d — Position %d",
		payload.label or payload.modeId,
		payload.total,
		payload.maxPlayers,
		payload.position
	)
end

local function showQueue(payload)
	title.Text = "Warteschlange"
	status.Text = formatStatus(payload)
	gui.Enabled = true
	leaveButton.Visible = true
end

local function hideQueue()
	gui.Enabled = false
	status.Text = ""
end

Remotes.QueueUpdate.OnClientEvent:Connect(function(payload)
	if payload.status == "left" then
		hideQueue()
		return
	end
	if payload.status == "starting" then
		status.Text = formatStatus(payload)
		leaveButton.Visible = false
		gui.Enabled = true
		return
	end
	showQueue(payload)
end)

Remotes.HubState.OnClientEvent:Connect(function(state)
	if state.phase == "arena" then
		hideQueue()
	end
end)

leaveButton.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
	hideQueue()
end)
