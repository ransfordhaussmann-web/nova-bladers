local function formatPlayerList(names)
	if #names == 0 then
		return "—"
	end
	return table.concat(names, ", ")
end

local function showQueue(payload)
	gui.Enabled = true
	title.Text = "Warteschlange — " .. (payload.modeLabel or payload.modeId)

	local statusLine = string.format(
		"Spieler: %d / %d\n%s",
		payload.count or 0,
		payload.maxPlayers or 0,
		formatPlayerList(payload.playerNames or {})
	)

	if payload.pending or payload.arenaBusy then
		statusLine ..= "\n\nArena belegt — warte auf freien Slot..."
	elseif (payload.count or 0) < (payload.minPlayers or 1) then
		statusLine ..= "\n\nWarte auf weitere Spieler..."
	else
		statusLine ..= "\n\nMatch startet bald..."
	end

	statusLabel.Text = statusLine
end

local function hideQueue()
	gui.Enabled = false
	statusLabel.Text = ""
end

Remotes.QueueUpdate.OnClientEvent:Connect(function(payload)
	if not payload or payload.error then
		hideQueue()
		return
	end
	showQueue(payload)
end)

Remotes.HubState.OnClientEvent:Connect(function(state)
	if state.phase == "arena" then
		hideQueue()
	elseif state.phase == "hub" then
		hideQueue()
	end
end)

leaveButton.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
	hideQueue()
end)
