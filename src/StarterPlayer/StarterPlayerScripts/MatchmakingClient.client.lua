local leaveButton = Instance.new("TextButton")
leaveButton.Name = "LeaveButton"
leaveButton.Size = UDim2.fromOffset(120, 28)
leaveButton.Position = UDim2.fromOffset(8, 62)
leaveButton.BackgroundColor3 = Color3.fromRGB(180, 70, 70)
leaveButton.Font = Enum.Font.GothamBold
leaveButton.TextSize = 13
leaveButton.TextColor3 = Color3.new(1, 1, 1)
leaveButton.Text = "Queue verlassen"
leaveButton.Parent = panel

local leaveCorner = Instance.new("UICorner")
leaveCorner.CornerRadius = UDim.new(0, 6)
leaveCorner.Parent = leaveButton

local function showQueue(payload)
	if payload.inQueue == false or payload.status == "starting" then
		gui.Enabled = false
		return
	end

	gui.Enabled = true
	title.Text = payload.modeLabel and ("Queue: " .. payload.modeLabel) or "Matchmaking"
	status.Text = payload.message or "Warte auf Match..."
end

Remotes.QueueUpdate.OnClientEvent:Connect(showQueue)

Remotes.HubState.OnClientEvent:Connect(function(state)
	if state.phase == "hub" then
		gui.Enabled = false
	elseif state.phase == "queue" then
		gui.Enabled = true
		if state.modeLabel then
			title.Text = "Queue: " .. state.modeLabel:gsub("^Modus: ", "")
		end
	elseif state.phase == "arena" then
		gui.Enabled = false
	end
end)

leaveButton.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
end)
