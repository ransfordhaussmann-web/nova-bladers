local function statusText(payload)
	local lines = {
		string.format("%s — %d/%d Spieler", payload.modeLabel, payload.count, payload.maxPlayers),
	}

	if payload.status == "pending" then
		table.insert(lines, "Arena belegt — warte auf freie Arena")
	elseif payload.fillSecondsLeft then
		table.insert(lines, string.format("Start in %ds (min. %d)", payload.fillSecondsLeft, payload.minPlayers))
	else
		table.insert(lines, "Warte auf Mitspieler...")
	end

	return table.concat(lines, "\n")
end

Remotes.QueueUpdate.OnClientEvent:Connect(function(payload)
	if not payload.inQueue then
		gui.Enabled = false
		return
	end

	gui.Enabled = true
	title.Text = "In Queue: " .. payload.modeLabel
	status.Text = statusText(payload)
end)

leaveButton.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
	gui.Enabled = false
end)
