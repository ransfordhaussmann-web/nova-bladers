local STATUS_TEXT = {
	waiting = "Warte auf Spieler…",
	ready = "Match startet gleich…",
	pending = "Arena belegt — du bist vorgemerkt",
}

local function hideQueue()
	gui.Enabled = false
end

local function showQueue(payload)
	gui.Enabled = true
	title.Text = string.format("Warteschlange — %s", payload.modeLabel or payload.modeId or "?")
	status.Text = string.format(
		"%s\nSpieler: %d / %d",
		STATUS_TEXT[payload.status] or STATUS_TEXT.waiting,
		payload.queued or 0,
		payload.maxPlayers or 0
	)
end

Remotes.QueueUpdate.OnClientEvent:Connect(function(payload)
	if payload.inQueue == false then
		hideQueue()
		return
	end
	showQueue(payload)
end)

Remotes.HubState.OnClientEvent:Connect(function(state)
	if state.phase == "arena" then
		hideQueue()
	end
end)

leaveButton.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
	hideQueue()
end)
