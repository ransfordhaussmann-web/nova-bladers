local function hideQueue()
	gui.Enabled = false
end

local function showQueue(payload)
	if not payload or not payload.modeId then
		hideQueue()
		return
	end

	gui.Enabled = true
	title.Text = "Warteschlange — " .. (payload.label or payload.modeId)

	local lines = {
		string.format("%d / %d Spieler", payload.count or 0, payload.maxPlayers or 1),
	}
	if payload.pending then
		table.insert(lines, "Arena belegt — warte auf freien Slot")
	else
		table.insert(lines, string.format("Start in max. %ds nach Mindestanzahl", payload.fillTimeout or 12))
	end
	status.Text = table.concat(lines, "\n")
end

Remotes.QueueUpdate.OnClientEvent:Connect(function(payload)
	if payload.inQueue == false or not payload.modeId then
		hideQueue()
		return
	end
	showQueue(payload)
end)

Remotes.HubState.OnClientEvent:Connect(function(state)
	if state.phase == "arena" then
		hideQueue()
	end
end)

leaveBtn.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
	hideQueue()
end)
