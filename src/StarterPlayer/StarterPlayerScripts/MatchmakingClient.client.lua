local function hideQueue()
	gui.Enabled = false
end

local function showQueue(payload)
	gui.Enabled = true
	title.Text = payload.modeLabel or "Warteschlange"

	local lines = {}
	if payload.pending then
		table.insert(lines, "Arena belegt — warte auf freien Slot...")
	end

	if payload.status == "starting" then
		table.insert(lines, "Match startet gleich!")
	elseif payload.count and payload.target then
		table.insert(lines, string.format("Spieler: %d / %d", payload.count, payload.target))
		if payload.fillRemaining and payload.fillRemaining > 0 then
			table.insert(lines, string.format("Start in ca. %ds", math.ceil(payload.fillRemaining)))
		elseif payload.count < payload.target then
			table.insert(lines, "Warte auf weitere Spieler...")
		end
	end

	status.Text = table.concat(lines, "\n")
end

Remotes.QueueUpdate.OnClientEvent:Connect(function(payload)
	if not payload or payload.status == "left" then
		hideQueue()
		return
	end
	showQueue(payload)
end)

leaveButton.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
	hideQueue()
end)
