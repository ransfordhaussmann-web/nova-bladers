local function formatQueueText(payload)
	local queue = payload.queue
	if not queue then
		return ""
	end

	local lines = {
		string.format("%s — %d/%d Spieler", queue.modeLabel, queue.count, queue.maxPlayers),
	}

	if payload.status == "pending" then
		table.insert(lines, "Arena belegt — warte auf Start...")
	elseif queue.fillTimeout and queue.count >= queue.minPlayers and queue.count < queue.maxPlayers then
		table.insert(lines, string.format("FFA füllt sich (%ds Timeout)", queue.fillTimeout))
	end

	if #queue.players > 0 then
		table.insert(lines, table.concat(queue.players, ", "))
	end

	return table.concat(lines, "\n")
end

local function applyQueueState(payload)
	if not payload.inQueue then
		gui.Enabled = false
		return
	end

	gui.Enabled = true
	if payload.status == "pending" then
		title.Text = "Warteschlange (Pending)"
	else
		title.Text = "Warteschlange"
	end
	statusLabel.Text = formatQueueText(payload)
end

Remotes.QueueUpdate.OnClientEvent:Connect(applyQueueState)

leaveButton.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
	gui.Enabled = false
end)
