local function formatStatus(queue)
	local lines = {
		string.format("%s — %d/%d Spieler", queue.label, queue.count, queue.maxPlayers),
	}

	if queue.status == "pending" then
		table.insert(lines, "Arena belegt — warte auf freien Slot...")
	elseif queue.status == "filling" and queue.fillSecondsLeft then
		table.insert(lines, string.format("Start in %ds (min. %d)", queue.fillSecondsLeft, queue.minPlayers))
	elseif queue.count < queue.minPlayers then
		table.insert(lines, string.format("Benötigt %d Spieler", queue.minPlayers))
	else
		table.insert(lines, "Match startet gleich...")
	end

	if #queue.players > 0 then
		table.insert(lines, table.concat(queue.players, ", "))
	end

	return table.concat(lines, "\n")
end

