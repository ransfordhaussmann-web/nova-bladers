local function formatStatus(payload)
	if payload.status == "starting" then
		return "Match startet gleich..."
	end
	if payload.status == "pending" then
		return payload.message or "Arena belegt — Warte auf freie Arena"
	end

	local lines = {
		string.format("%s — %d/%d Spieler", payload.modeLabel or "Queue", payload.queueSize or 0, payload.required or 1),
	}
	if payload.message then
		table.insert(lines, payload.message)
	elseif payload.modeId == "ffa" and payload.queueSize and payload.required and payload.queueSize < payload.required then
		table.insert(lines, "Warte auf weitere Spieler...")
	end
	return table.concat(lines, "\n")
end

local function applyQueueState(payload)
	if not payload.inQueue then
		gui.Enabled = false
		return
	end

	gui.Enabled = true
	title.Text = string.format("Queue: %s", payload.modeLabel or payload.modeId or "?")
	status.Text = formatStatus(payload)
end

Remotes.QueueUpdate.OnClientEvent:Connect(function(payload)
	applyQueueState(payload)
end)

