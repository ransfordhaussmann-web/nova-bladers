local function formatStatus(payload)
	local countText = string.format("%d / %d Spieler", payload.players, payload.maxPlayers)

	if payload.status == "pending" or payload.pending then
		return countText .. "\nWarte auf freie Arena..."
	elseif payload.status == "filling" and payload.fillTimeLeft then
		return countText .. string.format("\nStart in %ds (Warteschlange füllt sich)", payload.fillTimeLeft)
	elseif payload.players < payload.minPlayers then
		return countText .. string.format("\nNoch %d Spieler benötigt", payload.minPlayers - payload.players)
	end

	return countText .. "\nMatch startet gleich..."
end

local function showQueue(payload)
	gui.Enabled = true
	title.Text = "Warteschlange — " .. (payload.modeLabel or payload.modeId)
	status.Text = formatStatus(payload)
end

local function hideQueue()
	gui.Enabled = false
end

Remotes.QueueUpdate.OnClientEvent:Connect(function(payload)
	if not payload then
		hideQueue()
		return
	end
	showQueue(payload)
end)

Remotes.HubState.OnClientEvent:Connect(function(state)
	if state.phase == "arena" then
		hideQueue()
	end
end)

leaveButton.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
	hideQueue()
end)
