local function statusText(payload)
	local lines = {
		string.format("%s — %d / %d Spieler", payload.modeLabel, payload.queued, payload.max),
	}

	if payload.status == MatchmakingConfig.STATUS.WAITING then
		if payload.fillSecondsLeft then
			table.insert(lines, string.format("Start in %ds (oder bei %d Spielern)", payload.fillSecondsLeft, payload.max))
		else
			table.insert(lines, string.format("Warte auf %d Spieler...", payload.needed))
		end
	elseif payload.status == MatchmakingConfig.STATUS.PENDING then
		table.insert(lines, "Arena belegt — Match startet gleich")
	elseif payload.status == MatchmakingConfig.STATUS.STARTING then
		table.insert(lines, "Match startet...")
	end

	return table.concat(lines, "\n")
end

local function applyQueueState(payload)
	if not payload.inQueue then
		gui.Enabled = false
		return
	end

	gui.Enabled = true
	title.Text = "Warteschlange: " .. payload.modeLabel
	statusLabel.Text = statusText(payload)
end

Remotes.QueueUpdate.OnClientEvent:Connect(applyQueueState)

Remotes.HubState.OnClientEvent:Connect(function(state)
	if state.phase == "arena" then
		gui.Enabled = false
	end
end)

leaveButton.MouseButton1Click:Connect(function()
	Remotes.QueueLeave:FireServer()
end)
